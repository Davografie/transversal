# ── Step building + execution (dry-run aware) ────────

def _step(op: str, query: str, variables: dict, describe: str) -> dict:
    return {"op": op, "query": query, "variables": variables, "describe": describe}


def _fill(obj: Any, last_id: str | None) -> Any:
    """Return a copy of ``obj`` with ``_AUTO_ID`` values replaced by ``last_id``."""
    import copy
    filled = copy.deepcopy(obj)
    _fill_in(filled, last_id)
    return filled


def _fill_in(obj: Any, last_id: str | None) -> None:
    if isinstance(obj, dict):
        for k, v in obj.items():
            if v == _AUTO_ID:
                obj[k] = last_id
            else:
                _fill_in(v, last_id)
    elif isinstance(obj, list):
        for i, v in enumerate(obj):
            if v == _AUTO_ID:
                obj[i] = last_id
            else:
                _fill_in(v, last_id)


def _run_steps(steps: list[dict], dry_run: bool) -> dict:
    """Run an ordered list of GraphQL steps.

    ``dry_run=true`` returns the plan without executing. Otherwise steps execute
    in order; each createEntity step records its generated id so later steps can
    reference it via ``_AUTO_ID``.
    """
    if dry_run:
        return {
            "dry_run": True,
            "plan": [
                {"op": s["op"], "describe": s["describe"], "variables": s["variables"]}
                for s in steps
            ],
        }

    last_id: str | None = None
    results: list[dict] = []
    for s in steps:
        data = _graphql(s["query"], _fill(s["variables"], last_id))
        if s["op"] == "createEntity":
            last_id = data["createEntity"]["id"]
        results.append(data)
    return {"dry_run": False, "results": results}


def _create_entity_step(
    etype: str, name: str, universe: str, location: str | None = None, razmerit: int = 0
) -> dict:
    return _step(
        "createEntity",
        _MUT_CREATE_ENTITY,
        {
            "input": {
                "name": name,
                "type": etype,
                "universe": universe,
                "location": location,
                "razmerit": razmerit,
            }
        },
        f"create {etype} '{name}'",
    )


