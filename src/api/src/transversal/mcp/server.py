"""MCP server — exposes Transversal tools over stdio.

Architecture
------------
All *state* operations (entity CRUD, relationships) go through the GraphQL API
over HTTP — the API is the single source of truth and owns the business logic.
Only *dice resolution* runs locally, and it imports the exact ``dice_resolver``
module the API itself imports, so there is no logic divergence.

Content authoring workflow (fictional worldbuilding) is the primary use case:
create universes → factions → locations → GMCs → assets, in that order.

Every mutating tool accepts ``dry_run`` (default ``true``). With ``dry_run=false``
the tool returns the ordered GraphQL operations it *would* run, without touching
the database — so an agent (or a human) can review the plan and align with the
GM's vision before committing.

Tool groups
-----------
  Content (API):  create_universe, create_faction, create_location,
                  create_gmc, create_asset, create_relationship,
                  get_entity, query_entities
  Dice (local):   roll_dice, pick_total, pick_effect_die, compare_totals
"""

