_RELATIONS_TS_CACHE: str | None = None


def _relations_traitset_id() -> str:
    """Resolve the id of the 'relations' trait set (rank/role live there)."""
    global _RELATIONS_TS_CACHE
    if _RELATIONS_TS_CACHE is None:
        data = _graphql(_QUERY_TRAITSETS)
        for ts in data.get("traitsets", []):
            if ts.get("name") == "relations":
                _RELATIONS_TS_CACHE = ts["id"]
                break
        if _RELATIONS_TS_CACHE is None:
            raise RuntimeError("relations trait set not found")
    return _RELATIONS_TS_CACHE


def set_rank_role(args: dict) -> dict:
    """Attach rank and/or role traits to a relationship edge (conspyramid node).

    Rank/role are relationship-scoped traits on the membership edge, read by the
    faction canvas. Conspyramid level 1 is d4 (the ladder: 1=d4, 2=d6, 3=d8,
    4=d10, 5=d12, 6=d12); pass ``rank_die`` explicitly for full control.
    """
    from_id = args["from_id"]
    to_id = args["to_id"]
    rel_type = args.get("rel_type", "membership")
    rank_die = args.get("rank_die")
    role = args.get("role", "")
    traitset = _relations_traitset_id()

    steps = []
    if rank_die:
        steps.append(_step(
            "addRelationshipTrait",
            _MUT_ADD_RELATIONSHIP_TRAIT,
            {
                "from": from_id, "to": to_id, "relType": rel_type,
                "traitId": "trait-rel-rank", "die": rank_die,
                "ts": traitset, "stmt": "",
            },
            f"rank {from_id} as {rank_die} in {to_id}",
        ))
    if role:
        steps.append(_step(
            "addRelationshipTrait",
            _MUT_ADD_RELATIONSHIP_TRAIT,
            {
                "from": from_id, "to": to_id, "relType": rel_type,
                "traitId": "trait-role-cd1b", "die": "D4",
                "ts": traitset, "stmt": role,
            },
            f"role '{role}' for {from_id} in {to_id}",
        ))
    return _run_steps(steps, args.get("dry_run", True))


