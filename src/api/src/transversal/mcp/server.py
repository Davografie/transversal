def update_trait_setting(args: dict) -> dict:
    """Mutate an existing trait setting (dice, rating, notes, order, GM flags).

    Re-anchoring is a *pair*: ``from_type: "traitsetting"`` with
    ``parent_traitsetting_id`` to move a sub-trait into a container,
    ``"projection"`` with ``projection_id``, or ``"entity"`` to lift it back out.
    The resolver acts on ``from_type`` alone, so a parent or projection without it
    would be silently ignored — refused here instead of quietly doing nothing.

    ``trait_id`` changes the instance's *definition* (its registry trait). The
    instance keeps its dice, statement, notes, tags and grants; its set follows the
    new definition. The rules (a container may only become another container, and a
    definition the owner already holds is not a legal destination) are enforced by
    the same function the ``change_trait`` effect uses.
    """
    if args.get("from_type") is None and (
        args.get("parent_traitsetting_id") is not None or args.get("projection_id") is not None
    ):
        raise ValueError(
            "re-anchoring needs from_type: 'traitsetting' + parent_traitsetting_id, "
            "'projection' + projection_id, or 'entity'"
        )
    input_ = {}
    for key, gql_key in (
        ("dice", "dice"), ("rating_type", "ratingType"),
        ("statement", "statement"), ("polarity", "polarity"), ("notes", "notes"),
        ("tags", "tags"), ("capacity", "capacity"), ("order", "order"),
        ("enabled", "enabled"), ("known_to", "knownTo"), ("sfx_ids", "sfxIds"),
        ("from_type", "fromType"), ("projection_id", "projectionId"),
        ("parent_traitsetting_id", "parentTraitsettingId"),
        ("trait_id", "traitId"),
    ):
        if args.get(key) is not None:
            value = args[key]
            if key in ("rating_type", "polarity", "from_type"):
                value = _enum(value)
            elif key in ("dice", "capacity"):
                value = _enums(value)
            input_[gql_key] = value
    variables = {"id": args["id"], "input": input_}
    return _call_mutation("updateTraitSetting", _MUT_UPDATE_TRAIT_SETTING, variables,
                          args.get("dry_run", True), "updateTraitSetting")


def remove_trait_setting(args: dict) -> dict:
    """Remove a trait setting from an entity.

    The mutation answers with a bare boolean, and **no query fetches a setting by
    its own id** — so pass ``entity_id`` and the removal is confirmed by reading
    the owner's settings back and checking the id is gone. Without it the response
    says plainly that nothing was checked, rather than implying it was observed.
    """
    variables = {"id": args["id"]}
    result = _call_mutation("removeTraitSetting", _MUT_REMOVE_TRAIT_SETTING, variables,
                            args.get("dry_run", True), "removeTraitSetting")
    if args.get("dry_run", True):
        return result
    entity_id = args.get("entity_id")
    if not entity_id:
        return _read_back(result, False, "not checked",
                          note="pass entity_id to confirm the removal by reading the "
                               "owner's settings back")
    remaining = [
        t for t in ((_graphql(_QUERY_ENTITY_BUILD, {"id": entity_id}).get("entity") or {})
                    .get("traitSettings") or [])
        if t.get("id") == args["id"]
    ]
    return _read_back(result, not remaining, f"entity({entity_id}).traitSettings",
                      note="the setting is still present" if remaining else "")


