def _call_mutation(
    name: str, mutation: str, variables: dict, dry_run: bool, result_key: str = ""
) -> dict:
    """Run a GraphQL mutation, or (dry_run) return its would-be input."""
    if dry_run:
        return {"dry_run": True, "mutation": name, "variables": variables}
    data = _graphql(mutation, variables)
    return data.get(result_key, data) if result_key else data


