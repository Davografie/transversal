# ── API client ───────────────────────────────────────

# The Transversal API base URL. Defaults to the docker-compose host mapping
# (tv2_api → 8085). Override via TRANSVERSAL_API_URL when the MCP client does
# not run on the docker host.
API_URL = os.environ.get("TRANSVERSAL_API_URL", "http://localhost:8085").rstrip("/")
GRAPHQL_URL = f"{API_URL}/api/v1/graphql"

# Sentinel replaced by the id returned from the most recent createEntity step.
_AUTO_ID = "<auto-generated-id>"


def _graphql(query: str, variables: dict | None = None) -> dict:
    """Execute a GraphQL query/mutation against the API. Raises on any error."""
    resp = httpx.post(
        GRAPHQL_URL,
        json={"query": query, "variables": variables or {}},
        timeout=30.0,
    )
    resp.raise_for_status()
    payload = resp.json()
    if "errors" in payload:
        raise RuntimeError(json.dumps(payload["errors"]))
    return payload.get("data", {})


def _rest(path: str) -> Any:
    """GET a REST endpoint from the API (read-only). Raises on any error."""
    resp = httpx.get(f"{API_URL}{path}", timeout=30.0)
    resp.raise_for_status()
    return resp.json()


def _rest_post(path: str, payload: dict) -> Any:
    """POST a JSON body to a REST endpoint. Raises on any error."""
    resp = httpx.post(f"{API_URL}{path}", json=payload, timeout=30.0)
    resp.raise_for_status()
    return resp.json()


def _rest_delete(path: str) -> Any:
    """DELETE a REST endpoint. Raises on any error."""
    resp = httpx.delete(f"{API_URL}{path}", timeout=30.0)
    resp.raise_for_status()
    return resp.json()


def _rest_put(path: str, payload: Any) -> Any:
    """PUT a JSON body to a REST endpoint. Raises on any error."""
    resp = httpx.put(f"{API_URL}{path}", json=payload, timeout=30.0)
    resp.raise_for_status()
    return resp.json()


