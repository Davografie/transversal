# Protocol version this server speaks. We pin the 2024-11-05 baseline: it is the
# widest-supported version and only requires text tool results (which is all we
# produce). Clients that request a newer version negotiate down to this.
PROTOCOL_VERSION = "2024-11-05"
SERVER_NAME = "transversal"
SERVER_VERSION = "0.2.0"

# MCP notifications the server acknowledges. Notifications carry no `id` and MUST
# receive no response; acknowledging them here is purely documentation — they are
# silently dropped below.
_NOOP_NOTIFICATIONS = {
    "notifications/initialized",
    "notifications/cancelled",
    "notifications/roots/list_changed",
    "logging/setLevel",
}


# ── JSON-RPC handler (stdio) ────────────────────────

def _jsonrpc_error(req_id, code: int, message: str) -> dict:
    return {"jsonrpc": "2.0", "id": req_id, "error": {"code": code, "message": message}}


def handle_initialize(req_id, params: dict) -> dict:
    """Respond to the MCP ``initialize`` handshake."""
    return {
        "jsonrpc": "2.0",
        "id": req_id,
        "result": {
            "protocolVersion": PROTOCOL_VERSION,
            "capabilities": {"tools": {}},
            "serverInfo": {"name": SERVER_NAME, "version": SERVER_VERSION},
        },
    }


def handle_request(request: dict) -> dict | None:
    """Handle a single JSON-RPC request.

    Returns ``None`` for notifications (which receive no response).
    """
    method = request.get("method", "")
    req_id = request.get("id")

    # ── Notifications: no `id` → no response, never error ──
    if "id" not in request:
        return None

    if method == "initialize":
        return handle_initialize(req_id, request.get("params", {}))

    if method == "ping":
        return {"jsonrpc": "2.0", "id": req_id, "result": {}}

    if method == "tools/list":
        return {
            "jsonrpc": "2.0",
            "id": req_id,
            "result": {"tools": list(TOOL_SCHEMAS.values())},
        }

    if method == "tools/call":
        params = request.get("params", {})
        tool_name = params.get("name", "")
        arguments = params.get("arguments", {})

        if tool_name not in TOOLS:
            return _jsonrpc_error(req_id, -32602, f"Tool '{tool_name}' not found")

        try:
            result = TOOLS[tool_name](arguments)
            return {
                "jsonrpc": "2.0",
                "id": req_id,
                "result": {
                    "content": [{"type": "text", "text": json.dumps(result)}],
                    "isError": False,
                },
            }
        except Exception as e:
            return _jsonrpc_error(req_id, -32000, str(e))

    return _jsonrpc_error(req_id, -32601, f"Method '{method}' not supported")


def main():
    """Run the MCP server over stdio."""
    for line in sys.stdin:
        line = line.strip()
        if not line:
            continue
        try:
            request = json.loads(line)
        except json.JSONDecodeError:
            continue

        try:
            response = handle_request(request)
        except Exception as e:
            response = _jsonrpc_error(request.get("id"), -32603, f"Internal error: {e}")

        # Notifications get no response.
        if response is not None:
            sys.stdout.write(json.dumps(response) + "\n")
            sys.stdout.flush()


if __name__ == "__main__":
    main()
